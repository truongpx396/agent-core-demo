CUSTOMER = BillingCustomer("acme-tenant", "stripe", "cus_9")
PRODUCT = CreditProduct("stripe", "price_pack_100", __import__("decimal").Decimal("100"))


def with_api(api: FakeStripeApi | None = None, **kwargs) -> tuple[StripeProvider, FakeStripeApi]:
    api = api or FakeStripeApi()
    return StripeProvider(SECRET, api_key=kwargs.pop("api_key", api.api_key), transport=api.transport, **kwargs), api


async def checkout(p: StripeProvider, key: str = "k1"):
    return await p.create_checkout(CUSTOMER, PRODUCT, idempotency_key=key, success_url="https://app/ok", cancel_url="https://app/no")


class TestTheCheckoutRequest:
    async def test_it_asks_for_one_unit_of_the_packs_price_for_the_stripe_customer(self):
        p, api = with_api()

        await checkout(p)

        (form,) = api.forms
        assert form == {
            "mode": "payment", "line_items[0][price]": "price_pack_100", "line_items[0][quantity]": "1", "customer": "cus_9",
            "success_url": "https://app/ok", "cancel_url": "https://app/no", "metadata[product_ref]": "price_pack_100",
        }

    async def test_it_authenticates_with_the_secret_key_and_sends_the_idempotency_key_to_the_documented_endpoint(self):
        p, api = with_api()

        await checkout(p, "attempt-77")

        (request,) = api.requests
        assert (request.method, request.url.host, request.url.path) == ("POST", "api.stripe.com", "/v1/checkout/sessions")
        assert request.headers["authorization"] == f"Bearer {api.api_key}"
        assert request.headers["idempotency-key"] == "attempt-77"

    async def test_neither_an_amount_nor_a_credit_count_nor_a_tenant_is_sent(self):
        """What a pack is WORTH is the catalog's decision and what it COSTS is the price's: the request names the price and nothing else."""
        p, api = with_api()

        await checkout(p)

        wire = json.dumps(api.forms)
        assert "acme-tenant" not in wire and "credits" not in wire and "amount" not in wire and "unit_amount" not in wire

    async def test_it_returns_the_sessions_id_and_hosted_url(self):
        p, _ = with_api()

        session = await checkout(p)

        assert session.session_ref == "cs_test_0001" and session.url == "https://checkout.stripe.test/c/pay/cs_test_0001"

    async def test_the_same_key_with_different_parameters_is_refused_not_a_second_purchase(self):
        p, api = with_api()
        await checkout(p, "k1")

        with pytest.raises(CheckoutError) as caught:
            await p.create_checkout(CUSTOMER, PRODUCT, idempotency_key="k1", success_url="https://elsewhere/ok", cancel_url="https://app/no")

        assert caught.value.retryable is False and caught.value.code == "idempotency_error"
        assert len(api.sessions) == 1


class TestARefusedCheckoutSaysWhetherToTryAgain:
    @pytest.mark.parametrize(
        ("status", "retryable"),
        [(400, False), (401, False), (402, False), (403, False), (404, False), (409, True), (429, True), (500, True), (502, True), (503, True)],
    )
    async def test_the_status_decides(self, status, retryable):
        api = FakeStripeApi()
        api.script(httpx.Response(status, json={"error": {"type": "api_error", "code": "some_code", "message": "words that must not be repeated"}}))
        p, _ = with_api(api)

        with pytest.raises(CheckoutError) as caught:
            await checkout(p)

        assert caught.value.retryable is retryable and caught.value.status == status and caught.value.code == "some_code"

    async def test_stripes_own_words_and_the_key_never_reach_the_message(self):
        """A client error can quote a key fragment or a URL, and the message ends up in logs."""
        api = FakeStripeApi()
        api.script(httpx.Response(401, json={"error": {"type": "invalid_request_error", "message": "Invalid API Key provided: sk_test_****abcd"}}))
        p, _ = with_api(api)

        with pytest.raises(CheckoutError) as caught:
            await checkout(p)

        assert "sk_test" not in str(caught.value) and "Invalid API Key" not in str(caught.value)
        assert "401" in str(caught.value) and "invalid_request_error" in str(caught.value)

    async def test_the_name_of_the_field_stripe_objected_to_is_reported_so_a_400_can_be_diagnosed(self):
        api = FakeStripeApi()
        api.script(httpx.Response(400, json={"error": {"type": "invalid_request_error", "code": "resource_missing", "param": "line_items[0][price]", "message": "No such price: 'price_x'"}}))
        p, _ = with_api(api)

        with pytest.raises(CheckoutError) as caught:
            await checkout(p)

        assert "field line_items[0][price]" in str(caught.value) and "No such price" not in str(caught.value)

    @pytest.mark.parametrize("param", ["sk_test_abc def", "has a space", "x" * 101, "<script>", "a;b", "", 5])
    async def test_a_param_that_is_not_a_field_name_is_dropped_not_repeated(self, param):
        api = FakeStripeApi()
        api.script(httpx.Response(400, json={"error": {"type": "invalid_request_error", "param": param}}))
        p, _ = with_api(api)

        with pytest.raises(CheckoutError) as caught:
            await checkout(p)

        assert "field" not in str(caught.value)
        if isinstance(param, str) and param:
            assert param not in str(caught.value)

    async def test_a_network_failure_is_retryable(self):
        def unreachable(request):
            raise httpx.ConnectError("no route to host api.stripe.com with key sk_test_secret")

        p = StripeProvider(SECRET, api_key="sk_test_x", transport=httpx.MockTransport(unreachable))

        with pytest.raises(CheckoutError) as caught:
            await checkout(p)

        assert caught.value.retryable is True and caught.value.code == "network"
        assert "sk_test_secret" not in str(caught.value), "only the exception CLASS is reported"

    @pytest.mark.parametrize("body", [{}, {"id": "cs_1"}, {"url": "https://x"}, {"id": "", "url": ""}, {"id": 1, "url": 2}, [], "text"])
    async def test_a_200_with_no_usable_session_is_an_error_never_an_empty_session(self, body):
        api = FakeStripeApi()
        api.script(httpx.Response(200, json=body))
        p, _ = with_api(api)

        with pytest.raises(CheckoutError) as caught:
            await checkout(p)

        assert caught.value.code == "bad_response" and caught.value.retryable is False

    async def test_a_200_that_is_not_json_is_the_same_error(self):
        api = FakeStripeApi()
        api.script(httpx.Response(200, content=b"<html>"))
        p, _ = with_api(api)

        with pytest.raises(CheckoutError) as caught:
            await checkout(p)

        assert caught.value.code == "bad_response"

    async def test_without_an_api_key_nothing_is_attempted(self):
        api = FakeStripeApi()
        p, _ = with_api(api, api_key="")

        with pytest.raises(CheckoutError) as caught:
            await checkout(p)

        assert caught.value.code == "no_api_key" and caught.value.retryable is False
        assert api.requests == [], "a webhook-only deployment must not make a request it cannot authenticate"

    @pytest.mark.parametrize("key", ["", "k" * 256])
    async def test_an_idempotency_key_stripe_would_refuse_is_refused_here_first(self, key):
        p, api = with_api()

        with pytest.raises(CheckoutError) as caught:
            await checkout(p, key)

        assert caught.value.code == "bad_idempotency_key" and api.requests == []

    async def test_the_longest_key_stripe_allows_is_sent(self):
        p, api = with_api()

        await checkout(p, "k" * 255)

        assert len(api.requests[0].headers["idempotency-key"]) == 255


