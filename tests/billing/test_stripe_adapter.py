"""The Stripe adapter (app/billing/providers/stripe.py, specs/010 T029a): what the shared contract suite cannot say about it.

tests/billing/test_provider_contract.py holds every adapter to the same promises (refuse a forgery, name no tenant, store no buyer
details, echo what checkout set). This file is what is particular to Stripe's wire formats: its signature header, its event and object
shapes, its checkout request and its error replies. Hermetic: the signing is computed in-process and the HTTP is `httpx.MockTransport`.

## Why the signature tests do not just agree with the code

The vectors below were generated by STRIPE'S OWN PYTHON LIBRARY (`stripe.WebhookSignature.generate_signature_header`, stripe 16.0.0), run in
a throwaway environment outside this repository's dependencies. If this adapter and a test harness both misread the documented scheme the
same way, only a header produced by someone else would show it. The official verifier also accepts the "rolled" header and refuses the stale
one at the same instants used here.
"""
