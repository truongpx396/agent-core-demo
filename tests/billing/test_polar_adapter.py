def provider(secret: str = NEW_SECRET, now: float = T + 10, **kwargs) -> PolarProvider:
    kwargs.setdefault("access_token", "polar_oat_x")
    kwargs.setdefault("environment", "sandbox")
    return PolarProvider(secret, clock=lambda: now, **kwargs)


def headers(signature: str = NEW_SIG, *, event_id: str = MSG_ID, stamp: str = str(T)) -> dict[str, str]:
    return {"webhook-id": event_id, "webhook-timestamp": stamp, "webhook-signature": signature}


def parse(p: PolarProvider, hdrs: dict[str, str], body: bytes = KNOWN_BODY):
    return p.parse_webhook(hdrs, body)


def sign(body: bytes, *, event_id: str = MSG_ID, stamp: int = T, secret: str = NEW_SECRET) -> dict[str, str]:
    """Sign `body` the documented way with the new-scheme key, so only the mapping is under test."""
    key = base64.b64decode(secret.removeprefix("whsec_"))
    mac = base64.b64encode(hmac.new(key, f"{event_id}.{stamp}.".encode() + body, hashlib.sha256).digest()).decode()
    return headers(f"v1,{mac}", event_id=event_id, stamp=str(stamp))


class TestTheSignature:
    def test_a_header_generated_for_a_new_style_secret_is_accepted(self):
        (event,) = parse(provider(), headers(NEW_SIG))

        assert event.event_id == MSG_ID and event.raw_type == "order.refunded"

    def test_a_header_generated_for_a_legacy_secret_is_accepted_because_both_keys_are_tried(self):
        """A secret does not say whether it was made before or after 2026-09-08, so the key it means is whichever one verifies."""
        assert parse(provider(LEGACY_SECRET), headers(LEGACY_SIG))

    def test_a_rolled_header_with_an_old_signature_and_an_unknown_version_in_front_is_accepted_because_any_v1_may_match(self):
        assert parse(provider(), headers(f"{OLD_SIG} v2,AAAA {NEW_SIG}"))

    def test_a_signature_made_with_the_other_style_of_key_does_not_cross_secrets(self):
        with pytest.raises(InvalidSignature):
            parse(provider(LEGACY_SECRET), headers(NEW_SIG))

    def test_another_endpoints_secret_is_refused(self):
        with pytest.raises(InvalidSignature):
            parse(provider(OTHER_SECRET), headers(NEW_SIG))

    def test_a_version_other_than_v1_is_never_enough_even_for_an_arithmetically_right_signature(self):
        right_mac = NEW_SIG.split(",", 1)[1]

        for label in ("v2", "v0", "v1a", ""):
            with pytest.raises(InvalidSignature):
                parse(provider(), headers(f"{label},{right_mac}"))

    @pytest.mark.parametrize("missing", ["webhook-id", "webhook-timestamp", "webhook-signature"])
    def test_a_missing_header_is_refused(self, missing):
        hdrs = headers()
        del hdrs[missing]

        with pytest.raises(InvalidSignature):
            parse(provider(), hdrs)

    @pytest.mark.parametrize("stamp", ["", "abc", "nan", "inf", "-inf", "1e999", "0x10"])
    def test_a_malformed_timestamp_is_refused_not_a_crash(self, stamp):
        with pytest.raises(InvalidSignature):
            parse(provider(), headers(stamp=stamp))

    @pytest.mark.parametrize("signature", ["", "garbage", "v1,", "v1,!!!not-base64!!!", "v1,AAAA", ",,,", "v1", "  "])
    def test_a_malformed_signature_is_refused_not_a_crash(self, signature):
        with pytest.raises(InvalidSignature):
            parse(provider(), headers(signature))

    def test_the_window_is_symmetric_and_inclusive_exactly_as_polars_own_verifier_is(self):
        """Unlike Stripe's, Polar's verifier refuses a timestamp in the FUTURE too: the SDK accepts T-300 and T+300 and refuses T-301 and T+301."""
        for edge in (T + 300, T - 300):
            assert parse(provider(now=edge), headers())
        for beyond in (T + 301, T - 301):
            with pytest.raises(InvalidSignature):
                parse(provider(now=beyond), headers())

    def test_the_event_id_is_bound_into_the_mac_so_a_delivery_cannot_be_replayed_as_another_event(self):
        with pytest.raises(InvalidSignature):
            parse(provider(), headers(event_id="msg_someone_elses"))

    def test_the_timestamp_is_bound_into_the_mac_so_it_cannot_be_moved_to_make_an_old_delivery_look_fresh(self):
        with pytest.raises(InvalidSignature):
            parse(provider(now=T + 400), headers(stamp=str(T + 100)))

    def test_a_body_altered_after_signing_is_refused(self):
        with pytest.raises(InvalidSignature):
            parse(provider(), headers(), KNOWN_BODY.replace(b"ord_ka_1", b"ord_ka_2"))

    def test_header_names_are_case_insensitive(self):
        upper = {k.upper(): v for k, v in headers().items()}

        assert parse(provider(), upper)

    def test_a_tolerance_of_zero_is_refused_because_it_disables_the_check(self):
        with pytest.raises(ValueError, match="tolerance"):
            PolarProvider(NEW_SECRET, tolerance_seconds=0)

    def test_a_provider_with_no_secret_cannot_exist(self):
        with pytest.raises(ValueError, match="secret"):
            PolarProvider("")


class TestWhichKeysASecretCanMean:
    def test_a_whsec_secret_means_its_own_bytes_and_its_decoded_base64_remainder(self):
        assert _signing_keys(NEW_SECRET) == (NEW_SECRET.encode(), b"polar-known-answer-key!!")

    def test_a_secret_that_is_not_base64_means_only_its_own_bytes(self):
        assert _signing_keys("not base64 at all !!!") == (b"not base64 at all !!!",)

    def test_a_secret_that_decodes_to_itself_is_not_listed_twice(self):
        assert len(set(_signing_keys("whsec_"))) == len(_signing_keys("whsec_"))

    def test_the_32_character_secret_the_polar_cli_printed_in_the_sandbox_verifies_under_its_raw_bytes(self):
        """That secret had no `whsec_` prefix and was valid base64 by accident; the raw key is the one that matched Polar's signature."""
        secret = "AbCdEfGhIjKlMnOpQrStUvWxYz012345"
        body = b'{"type":"order.paid","data":{}}'
        mac = base64.b64encode(hmac.new(secret.encode(), f"{MSG_ID}.{T}.".encode() + body, hashlib.sha256).digest()).decode()

        assert parse(provider(secret), headers(f"v1,{mac}"), body)


def fixture(name: str) -> bytes:
    return (FIXTURES / f"polar_{name}.json").read_bytes()


def deliver(body: bytes | dict | list | str, *, event_id: str = "msg_1", p: PolarProvider | None = None):
    raw = body if isinstance(body, bytes) else json.dumps(body).encode()
    return (p or provider(now=T)).parse_webhook(sign(raw, event_id=event_id), raw)


def order(**overrides) -> dict:
    data = {
        "id": "ord_1", "status": "paid", "paid": True, "billing_reason": "purchase", "customer_id": "cus_1", "product_id": "prod_1",
        "total_amount": 1000, "net_amount": 900, "tax_amount": 100, "refunded_amount": 0, "currency": "usd",
    }
    return {"type": "order.paid", "timestamp": "2026-10-08T14:10:11.209162Z", "api_version": "2026-10", "data": {**data, **overrides}}


