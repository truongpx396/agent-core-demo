"""The Polar adapter (app/billing/providers/polar.py, specs/010 T029b): what the shared contract suite cannot say about it.

tests/billing/test_provider_contract.py holds every adapter to the same promises. This file is what is particular to Polar's wire
formats: its Standard Webhooks signature and the two keys a secret can mean, its Order and event shapes, and a Checkout API that has no
idempotency, so a retry is made safe by looking before creating. Hermetic: the signing is computed in-process and the HTTP is
`httpx.MockTransport`.

## Why the tests do not just agree with the code

  * The signature vectors were generated by the **Standard Webhooks library** and every one of them was verified under **Polar's own SDK**
    (`polar.webhooks._verify_signature`, polar-sdk 1.0.2) at the instants used here, in a throwaway environment outside this repository's
    dependencies. The SDK is also the oracle for the window: it accepts exactly T-300 and T+300 and refuses T-301 and T+301.
  * The payload fixtures in tests/billing/fixtures/polar_*.json were generated by **`polar trigger <event> --json --seed 7`**, Polar's own
    tooling building a payload from its own schema, so the adapter is shown real Order shapes (every field, the buyer's name, address and
    email included), not only dicts shaped by this file's author. The sample buyer is the generator's fiction. `--seed 7` gives every
    fixture the same order id, so a purchase and its refund really do share one.
"""
