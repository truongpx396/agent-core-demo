def with_api(api: FakePolarApi | None = None, **kwargs) -> tuple[PolarProvider, FakePolarApi]:
    api = api or FakePolarApi()
    kwargs.setdefault("access_token", api.token)
    kwargs.setdefault("environment", "sandbox")
    return PolarProvider(NEW_SECRET, transport=api.transport, **kwargs), api


async def checkout(p: PolarProvider, key: str = "k1", *, customer: BillingCustomer = CUSTOMER, product: CreditProduct = PRODUCT):
    return await p.create_checkout(customer, product, idempotency_key=key, success_url="https://app/ok", cancel_url="https://app/no")


def methods(api: FakePolarApi) -> list[str]:
    return [r.method for r in api.requests]


